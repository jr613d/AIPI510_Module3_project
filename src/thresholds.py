"""Compare classification cutoffs for the saved model on validation data.

Run: python -m src.thresholds [--tracking-mode online|offline|disabled]
The model outputs a churn probability; the threshold decides when that counts
as a "Yes". Nothing is retrained, and the test partition is never scored.
"""

import argparse
import json
from pathlib import Path

import joblib

from src.ingest import ROOT, load_config
from src.preprocess import prepare_splits
from src.tracking import MODES, log_threshold_table, tracking_settings
from src.train import validation_metrics


def threshold_rows(pipeline, validation, settings, candidates):
    if not isinstance(candidates, list) or not candidates:
        raise ValueError("threshold_selection.candidates must be a nonempty list.")
    rows = []
    for threshold in candidates:
        metrics = validation_metrics(pipeline, validation, {**settings, "threshold": threshold})
        counts = metrics["confusion_matrix"]
        rows.append({
            "threshold": threshold,
            "flagged": counts["true_positives"] + counts["false_positives"],
            "churners_caught": counts["true_positives"],
            "false_alarms": counts["false_positives"],
            "churners_missed": counts["false_negatives"],
            "precision": metrics["precision"], "recall": metrics["recall"],
        })
    return rows


def load_matching_model(config, source):
    """Use the saved model only if it came from this config's settings and data."""
    settings = config["training"]
    bundle = joblib.load(ROOT / settings["model_path"])  # Trusted local training output.
    saved = bundle["settings"]
    if (saved["numeric_features"] != settings["numeric_features"]
            or saved["categorical_features"] != settings["categorical_features"]
            or saved["logistic_regression"] != settings["logistic_regression"]):
        raise ValueError("The saved model does not match config.yaml; rerun python -m src.train.")
    if bundle["processed_sha256"] != source["sha256"]:
        raise ValueError("The saved model was trained on different data; rerun python -m src.train.")
    return bundle["pipeline"]


def write_summary(rows, section, source):
    summary = {"evaluation_partition": "validation", "test_evaluated": False,
               "data_sha256": source["sha256"], "rows": rows}
    json_path, markdown_path = ROOT / section["summary_json"], ROOT / section["summary_markdown"]
    json_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(json.dumps(summary, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    total = rows[0]["churners_caught"] + rows[0]["churners_missed"]
    lines = [
        "# Threshold selection (validation data only)", "",
        f"Generated by `python -m src.thresholds` for the saved model. "
        f"The validation data has {total} actual churners. The test partition was not used.", "",
        "| Threshold | Flagged | Churners caught | False alarms | Churners missed | Precision | Recall |",
        "| ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    lines += [f"| {r['threshold']:.2f} | {r['flagged']} | {r['churners_caught']} | {r['false_alarms']} | "
              f"{r['churners_missed']} | {r['precision']:.1%} | {r['recall']:.1%} |" for r in rows]
    markdown_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return markdown_path


def select_thresholds(config_path=ROOT / "config.yaml", tracking_mode=None):
    config, _ = load_config(config_path)
    tracking = tracking_settings(config, tracking_mode)
    section = config["threshold_selection"]
    splits, population = prepare_splits(config_path)
    source = population["source"]
    pipeline = load_matching_model(config, source)
    rows = threshold_rows(pipeline, splits["validation"], config["training"], section["candidates"])
    markdown_path = write_summary(rows, section, source)
    result = None
    if tracking["mode"] != "disabled":
        result = log_threshold_table(rows, data_sha256=source["sha256"], project=tracking["project"],
                                     entity=tracking["entity"], mode=tracking["mode"])
    return rows, markdown_path, result


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=ROOT / "config.yaml")
    parser.add_argument("--tracking-mode", choices=MODES,
                        help="Override tracking.mode in config.yaml for this run.")
    args = parser.parse_args(argv)
    try:
        _, markdown_path, result = select_thresholds(args.config, args.tracking_mode)
    except Exception as error:
        parser.exit(1, f"Threshold selection failed: {error}\n")
    print(markdown_path.read_text(encoding="utf-8"))
    if result:
        print(f"W&B {result['mode']} run recorded: {result['url'] or result['run_dir']}")


if __name__ == "__main__":
    main()
