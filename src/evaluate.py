"""Score the final model on the held-out TEST partition, exactly once.

Run: python -m src.evaluate [--tracking-mode online|offline|disabled]
Run this only after the model and threshold are chosen using validation data.
It refuses to run again once the test report exists, so the test set cannot
quietly become a second validation set.
"""

import argparse
import hashlib
import json
from pathlib import Path

from src.ingest import ROOT, load_config
from src.preprocess import prepare_splits
from src.thresholds import load_matching_model
from src.tracking import MODES, log_test_run, tracking_settings
from src.train import validation_metrics


def evaluate(config_path=ROOT / "config.yaml", tracking_mode=None):
    config, _ = load_config(config_path)
    tracking = tracking_settings(config, tracking_mode)
    settings, section = config["training"], config["final_evaluation"]
    json_path, markdown_path = ROOT / section["summary_json"], ROOT / section["summary_markdown"]
    if json_path.exists():
        raise ValueError(f"The test set was already evaluated ({section['summary_json']}). "
                         "It is used once; delete that report only if you deliberately start over.")
    model_path = ROOT / settings["model_path"]
    splits, population = prepare_splits(config_path)
    pipeline = load_matching_model(config, population["source"])
    import joblib  # Trusted local training output, loaded once more for its saved threshold.
    if joblib.load(model_path)["settings"]["threshold"] != settings["threshold"]:
        raise ValueError("The saved model's threshold differs from config.yaml; rerun python -m src.train.")
    metrics = validation_metrics(pipeline, splits["test"], settings)  # Same scoring code, test rows.
    report = {
        "evaluation_partition": "test", "test_evaluated": True,
        "test_customers": len(splits["test"]),
        "data_sha256": population["source"]["sha256"],
        "model_sha256": hashlib.sha256(model_path.read_bytes()).hexdigest(),
        "settings": settings, "metrics": metrics,
    }
    json_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(json.dumps(report, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    counts = metrics["confusion_matrix"]
    markdown_path.write_text("\n".join([
        "# Final test evaluation (one time)", "",
        f"Generated by `python -m src.evaluate`. The {report['test_customers']} test customers were "
        "never used for training, model selection, or threshold choice.", "",
        "| Measure | Value |", "| --- | ---: |",
        f"| ROC AUC | {metrics['roc_auc']:.4f} |",
        f"| Threshold | {metrics['threshold']} |",
        f"| Precision | {metrics['precision']:.1%} |",
        f"| Recall | {metrics['recall']:.1%} |",
        f"| Churners caught | {counts['true_positives']} |",
        f"| Churners missed | {counts['false_negatives']} |",
        f"| False alarms | {counts['false_positives']} |",
        f"| Correctly not flagged | {counts['true_negatives']} |",
    ]) + "\n", encoding="utf-8")
    result = None
    if tracking["mode"] != "disabled":
        result = log_test_run(report, project=tracking["project"], entity=tracking["entity"],
                              mode=tracking["mode"])
    return report, markdown_path, result


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=ROOT / "config.yaml")
    parser.add_argument("--tracking-mode", choices=MODES,
                        help="Override tracking.mode in config.yaml for this run.")
    args = parser.parse_args(argv)
    try:
        _, markdown_path, result = evaluate(args.config, args.tracking_mode)
    except Exception as error:
        parser.exit(1, f"Final evaluation failed: {error}\n")
    print(markdown_path.read_text(encoding="utf-8"))
    if result:
        print(f"W&B {result['mode']} run recorded: {result['url'] or result['run_dir']}")


if __name__ == "__main__":
    main()
