"""Compare model versions on validation data and record each one in W&B.

Run: python -m src.experiments [--tracking-mode online|offline|disabled]
Trains every combination of the C values and feature sets in config.yaml's
`experiments` section. Each version gets its own model file under
experiments.output_dir, so the main training outputs are never overwritten.
The test partition is never scored here.
"""

import argparse
from copy import deepcopy
import json
from pathlib import Path
import tempfile

import yaml

from src.ingest import ROOT, load_config
from src.tracking import MODES, log_training_run, tracking_settings
from src.train import train


def variants(config):
    """Yield (name, training settings) for every C value × feature set."""
    section = config.get("experiments")
    if not isinstance(section, dict):
        raise ValueError("config.yaml needs an experiments section.")
    c_values, feature_sets = section.get("C_values"), section.get("feature_sets")
    if not isinstance(c_values, list) or not c_values:
        raise ValueError("experiments.C_values must be a nonempty list.")
    if not isinstance(feature_sets, dict) or not feature_sets:
        raise ValueError("experiments.feature_sets must name at least one feature set.")
    output_dir = Path(section["output_dir"])
    for set_name, features in feature_sets.items():
        for c_value in c_values:
            name = f"{set_name}-C{c_value}"
            settings = deepcopy(config["training"])
            settings["numeric_features"] = list(features["numeric_features"])
            settings["categorical_features"] = list(features["categorical_features"])
            settings["logistic_regression"]["C"] = c_value
            settings["model_path"] = str(output_dir / name / "model.joblib")
            settings["validation_report"] = str(output_dir / name / "validation_report.json")
            yield name, set_name, settings


def summary_row(name, set_name, report):
    metrics = report["metrics"]
    return {
        "name": name, "feature_set": set_name,
        "input_count": len(report["input_features"]),
        "encoded_columns": report["encoded_feature_count"],
        "C": report["settings"]["logistic_regression"]["C"],
        "roc_auc": metrics["roc_auc"], "precision": metrics["precision"],
        "recall": metrics["recall"], "threshold": metrics["threshold"],
    }


def write_summary(rows, section, tracking_mode):
    summary = {"evaluation_partition": "validation", "test_evaluated": False,
               "tracking_mode": tracking_mode, "runs": rows}
    json_path, markdown_path = ROOT / section["summary_json"], ROOT / section["summary_markdown"]
    json_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(json.dumps(summary, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    lines = [
        "# Model-selection experiments (validation data only)", "",
        "Generated by `python -m src.experiments`. Precision and recall use the "
        f"threshold {rows[0]['threshold']}. The test partition was not used.", "",
        "| Run | Inputs | C | ROC AUC | Precision | Recall |",
        "| --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    lines += [f"| {r['name']} | {r['input_count']} | {r['C']} | {r['roc_auc']:.4f} | "
              f"{r['precision']:.2%} | {r['recall']:.2%} |" for r in rows]
    markdown_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return markdown_path


def run_experiments(config_path=ROOT / "config.yaml", tracking_mode=None):
    config, _ = load_config(config_path)
    tracking = tracking_settings(config, tracking_mode)
    planned = list(variants(config))  # Validate the whole plan before any training.
    rows = []
    with tempfile.TemporaryDirectory(prefix="churn-experiment-") as folder:
        for name, set_name, settings in planned:
            variant = deepcopy(config)
            variant["training"] = settings
            variant_path = Path(folder) / f"{name}.yaml"
            variant_path.write_text(yaml.safe_dump(variant, sort_keys=False), encoding="utf-8")
            _, report = train(variant_path)
            row = summary_row(name, set_name, report)
            if tracking["mode"] != "disabled":
                result = log_training_run(
                    report, ROOT / settings["model_path"], project=tracking["project"],
                    entity=tracking["entity"], mode=tracking["mode"],
                    run_name=name, group="model-selection",
                )
                row["wandb_run"] = result["url"] or result["run_id"]
            rows.append(row)
            print(f"{name}: validation ROC AUC {row['roc_auc']:.4f}")
    return rows, write_summary(rows, config["experiments"], tracking["mode"])


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=ROOT / "config.yaml")
    parser.add_argument("--tracking-mode", choices=MODES,
                        help="Override tracking.mode in config.yaml for these runs.")
    args = parser.parse_args(argv)
    try:
        _, markdown_path = run_experiments(args.config, args.tracking_mode)
    except Exception as error:  # Report any failure without claiming the comparison finished.
        parser.exit(1, f"Experiments failed: {error}\n")
    print(markdown_path.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
